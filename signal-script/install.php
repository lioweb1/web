function h(string $v): string { return htmlspecialchars($v, ENT_QUOTES, 'UTF-8'); }
function p(string $k, string $d = ''): string { return isset($_POST[$k]) && is_string($_POST[$k]) ? trim($_POST[$k]) : $d; }

