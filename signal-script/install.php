    try {
        $baseUrl = rtrim(p('base_url', $guessUrl), '/');
        $email = strtolower(p('admin_email'));
        $pass = (string)($_POST['admin_pass'] ?? '');
        if (!filter_var($email, FILTER_VALIDATE_EMAIL)) throw new RuntimeException('Enter a valid admin email.');
        if (strlen($pass) < 8) throw new RuntimeException('Admin password must be at least 8 characters.');
        if (!preg_match('#^https?://#', $baseUrl)) throw new RuntimeException('Site URL must start with http:// or https://');

        $CONFIG = [
            'base_url' => $baseUrl,
            'debug' => false,
            'db' => ['host' => p('db_host', 'localhost'), 'port' => (int)p('db_port', '3306'), 'name' => p('db_name'), 'user' => p('db_user'), 'pass' => (string)($_POST['db_pass'] ?? '')],
        ];
        define('BASE_URL', $baseUrl);
        define('APP_DEBUG', false);
        require __DIR__ . '/inc/functions.php';

        try {
            db();
        } catch (PDOException $e) {
            throw new RuntimeException('Database connection failed: ' . $e->getMessage());
        }

        $sql = (string)file_get_contents(__DIR__ . '/inc/schema.sql');
        $sql = preg_replace('/^--.*$/m', '', $sql) ?? '';
        foreach (array_filter(array_map('trim', explode(';', $sql))) as $stmt) {
            db()->exec($stmt);
        }

        save_setting('site_name', p('site_name', 'SignalPro') ?: 'SignalPro');
        save_setting('admin_email', $email);
        save_setting('cron_key', bin2hex(random_bytes(16)));
        if (p('td_key') !== '') save_setting('twelvedata_key', p('td_key'));

        if (q_val('SELECT id FROM users WHERE email = ?', [$email])) {
            q("UPDATE users SET password_hash = ?, role = 'admin', status = 'active' WHERE email = ?", [password_hash($pass, PASSWORD_DEFAULT), $email]);
        } else {
            q("INSERT INTO users (name, email, password_hash, role, ref_code) VALUES (?, ?, ?, 'admin', ?)", [p('admin_name', 'Admin') ?: 'Admin', $email, password_hash($pass, PASSWORD_DEFAULT), new_ref_code()]);
        }

        if (!empty($_POST['demo']) && !q_val('SELECT COUNT(*) FROM plans')) {
