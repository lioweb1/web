-- Signal Script database schema (MySQL 5.7+/MariaDB 10.3+)
CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(64) NOT NULL PRIMARY KEY,
  v MEDIUMTEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('user','admin') NOT NULL DEFAULT 'user',
  status ENUM('active','banned') NOT NULL DEFAULT 'active',
  premium_until DATETIME NULL,
  ref_code VARCHAR(16) NOT NULL UNIQUE,
  referred_by INT UNSIGNED NULL,
  referral_days_earned INT NOT NULL DEFAULT 0,
  marketing_optin TINYINT(1) NOT NULL DEFAULT 0,
  reset_token VARCHAR(64) NULL,
  reset_expires DATETIME NULL,
  last_login DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (referred_by)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS signals (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  market ENUM('binary','forex','crypto') NOT NULL,
  asset VARCHAR(32) NOT NULL,
  direction ENUM('BUY','SELL') NOT NULL,
  timeframe VARCHAR(10) NOT NULL DEFAULT '5min',
  entry DECIMAL(20,8) NOT NULL,
  stop_loss DECIMAL(20,8) NULL,
  take_profit DECIMAL(20,8) NULL,
  take_profit2 DECIMAL(20,8) NULL,
  expiry_minutes INT NOT NULL DEFAULT 5,
  expires_at DATETIME NOT NULL,
  confidence TINYINT UNSIGNED NOT NULL DEFAULT 60,
  analysis TEXT NULL,
  is_premium TINYINT(1) NOT NULL DEFAULT 0,
  source ENUM('auto','manual') NOT NULL DEFAULT 'manual',
  status ENUM('active','win','loss','expired','cancelled') NOT NULL DEFAULT 'active',
  close_price DECIMAL(20,8) NULL,
  closed_at DATETIME NULL,
  telegram_sent TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (status), INDEX (market), INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS posts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(200) NOT NULL UNIQUE,
  category VARCHAR(80) NULL,
  excerpt TEXT NULL,
  content MEDIUMTEXT NULL,
  image_url VARCHAR(500) NULL,
  meta_description VARCHAR(300) NULL,
  is_premium TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('draft','published') NOT NULL DEFAULT 'published',
  views INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pages (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(200) NOT NULL UNIQUE,
  content MEDIUMTEXT NULL,
  custom_css TEXT NULL,
  meta_description VARCHAR(300) NULL,
  in_menu TINYINT(1) NOT NULL DEFAULT 0,
  in_footer TINYINT(1) NOT NULL DEFAULT 1,
  bare TINYINT(1) NOT NULL DEFAULT 0,
  sort_order INT NOT NULL DEFAULT 0,
  status ENUM('draft','published') NOT NULL DEFAULT 'published',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS brokers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  logo_url VARCHAR(500) NULL,
  affiliate_url VARCHAR(1000) NOT NULL,
  bonus_text VARCHAR(200) NULL,
  description TEXT NULL,
  markets VARCHAR(120) NULL,
  min_deposit VARCHAR(40) NULL,
  rating DECIMAL(2,1) NOT NULL DEFAULT 4.5,
  featured TINYINT(1) NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 0,
  clicks INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS clicks (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  broker_id INT UNSIGNED NOT NULL,
  user_id INT UNSIGNED NULL,
  ip_hash CHAR(64) NULL,
  referer VARCHAR(500) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (broker_id), INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS plans (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  price DECIMAL(10,2) NOT NULL DEFAULT 0,
  currency VARCHAR(8) NOT NULL DEFAULT 'USD',
  duration_days INT NOT NULL DEFAULT 30,
  features TEXT NULL,
  highlight TINYINT(1) NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  sort_order INT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS payments (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  plan_id INT UNSIGNED NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  currency VARCHAR(8) NOT NULL DEFAULT 'USD',
  method VARCHAR(60) NOT NULL,
  txn_id VARCHAR(190) NOT NULL,
  note TEXT NULL,
  status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
  reviewed_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (user_id), INDEX (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS subscribers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  name VARCHAR(120) NULL,
  source VARCHAR(60) NULL,
  consent_text VARCHAR(500) NULL,
  ip VARCHAR(45) NULL,
  token CHAR(32) NOT NULL,
  status ENUM('subscribed','unsubscribed') NOT NULL DEFAULT 'subscribed',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS login_attempts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ip VARCHAR(45) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (ip, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS engine_log (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  level VARCHAR(10) NOT NULL DEFAULT 'info',
  message VARCHAR(1000) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
